<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

class CpanelPublish extends Command
{
    protected $signature = 'tisheh:cpanel-publish {--public-path= : Absolute path to the separate document root} {--force : Explicitly overwrite an existing site public directory} {--no-symlink : Use the restricted Laravel public-image fallback instead}';

    protected $description = 'Publish only public assets and a private-app launcher; never copies .env or vendor';

    public function handle(): int
    {
        $given = $this->option('public-path');
        $absolute = is_string($given)
            && (str_starts_with($given, '/') || str_starts_with($given, '\\\\') || preg_match('/^[A-Za-z]:[\\\\\/]/', $given) === 1);
        if (! $absolute || str_contains($given, "\0")) {
            $this->error('An absolute --public-path is required.');

            return self::FAILURE;
        }
        if (! is_dir($given)) {
            $this->error('Create the destination document-root directory first.');

            return self::FAILURE;
        }
        $dest = realpath($given);
        $base = realpath(base_path());
        $basePrefix = $base === false ? '' : rtrim($base, DIRECTORY_SEPARATOR).DIRECTORY_SEPARATOR;
        $destPrefix = $dest === false ? '' : rtrim($dest, DIRECTORY_SEPARATOR).DIRECTORY_SEPARATOR;
        if ($dest === false || $base === false || dirname($dest) === $dest || $dest === $base || str_starts_with($dest, $basePrefix) || str_starts_with($base, $destPrefix)) {
            $this->error('Destination must be separate from (and not contain) the private app.');

            return self::FAILURE;
        }
        if (! is_writable($dest)) {
            $this->error('Destination is not writable.');

            return self::FAILURE;
        }
        $existing = array_values(array_diff(scandir($dest), ['.', '..', '.well-known', 'cgi-bin']));
        if ($existing && ! $this->option('force')) {
            $this->error('Destination is not empty; backup it first. --force is required to overwrite public assets.');

            return self::FAILURE;
        }
        foreach (['.env', 'vendor', 'artisan', 'composer.json', 'bootstrap', 'app'] as $unsafe) {
            if (file_exists($dest.'/'.$unsafe)) {
                $this->error('Private files exist in destination; move them outside document root first.');

                return self::FAILURE;
            }
        }
        $link = $dest.'/storage';
        if ((file_exists($link) || is_link($link)) && (! is_link($link) || realpath($link) !== realpath(storage_path('app/public')))) {
            $this->error('Existing storage path is not this app public-storage link; refusing.');

            return self::FAILURE;
        }
        $source = base_path('public');
        foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($source, \FilesystemIterator::SKIP_DOTS)) as $file) {
            if (! $file->isFile() || $file->isLink()) {
                continue;
            }
            $relative = substr($file->getPathname(), strlen($source) + 1);
            if ($relative === 'index.php' || str_starts_with($relative, 'storage/')) {
                continue;
            }
            $target = $dest.'/'.$relative;
            File::ensureDirectoryExists(dirname($target));
            File::copy($file->getPathname(), $target);
        }
        $literal = var_export($base, true);
        $launcher = "<?php\n// Generated by TISHEH: only this launcher and public assets belong in document root.\ndefine('LARAVEL_START', microtime(true));\n\$base = $literal;\nif (!is_file(\$base.'/vendor/autoload.php')) { http_response_code(503); exit('Application dependencies are missing.'); }\nif (file_exists(\$maintenance = \$base.'/storage/framework/maintenance.php')) { require \$maintenance; }\nrequire \$base.'/vendor/autoload.php';\n\$app = require_once \$base.'/bootstrap/app.php';\n\$app->usePublicPath(__DIR__);\n\$app->handleRequest(\\Illuminate\\Http\\Request::capture());\n";
        File::put($dest.'/index.php', $launcher);
        if (! $this->option('no-symlink') && ! is_link($link)) {
            if (! function_exists('symlink') || ! @symlink(storage_path('app/public'), $link)) {
                $this->warn('Symlink unavailable: restricted /storage image routes will serve supported public images.');
            }
        }
        $this->info('Public assets and launcher published. No .env, source archive, database or vendor was copied.');
        $this->warn('Configure domain HTTPS and review the cPanel guide; publishing alone does not initialize the database.');

        return self::SUCCESS;
    }
}
